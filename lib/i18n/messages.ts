const CATALOGUE: Record<Lang, Partial<Record<MessageKey, string>>> = { en, am };

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = CATALOGUE[lang][key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** For completeness checks: keys with no Amharic yet. */
export function missingAmharicKeys(): MessageKey[] {
  return (Object.keys(en) as MessageKey[]).filter((key) => !(key in am));
}
